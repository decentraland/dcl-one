type Vars = Record<string, string | number>;

function pluralArm(body: string, count: number): string {
  const arms: Record<string, string> = {};
  const re = /(=\d+|zero|one|two|few|many|other)\s*\{((?:[^{}]|\{[^{}]*\})*)\}/g;
  for (const m of body.matchAll(re)) arms[m[1]!] = m[2]!;
  const rule = new Intl.PluralRules("en-US").select(count);
  const arm = arms[`=${count}`] ?? arms[rule] ?? arms.other ?? "";
  return arm.replace(/#/g, count.toLocaleString("en-US"));
}

export function format(message: string, vars: Vars = {}): string {
  let out = "";
  let i = 0;
  while (i < message.length) {
    const open = message.indexOf("{", i);
    if (open === -1) {
      out += message.slice(i);
      break;
    }
    out += message.slice(i, open);
    let depth = 0;
    let close = open;
    for (; close < message.length; close++) {
      if (message[close] === "{") depth++;
      else if (message[close] === "}" && --depth === 0) break;
    }
    const inner = message.slice(open + 1, close);
    const [name, kind, ...rest] = inner.split(",");
    const key = name!.trim();
    if (kind?.trim() === "plural") {
      const n = Number(vars[key] ?? 0);
      out += pluralArm(rest.join(","), Number.isFinite(n) ? n : 0);
    } else {
      out += key in vars ? String(vars[key]) : `{${key}}`;
    }
    i = close + 1;
  }
  return out;
}

export function hasMessage(key: string): boolean {
  return Object.prototype.hasOwnProperty.call(EN_MESSAGES, key);
}

export function t(key: string, vars?: Vars): string {
  const message = EN_MESSAGES[key];
  return message === undefined ? key : format(message, vars);
}
