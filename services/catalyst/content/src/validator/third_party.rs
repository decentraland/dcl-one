//! Third-party wearables and emotes: the merkle proof's content checks
//! (the declared `content` equals the entity's files, the committed hashing
//! keys, `entityHash` recomputed from the uploaded entity bytes in their own
//! key order) and the proof against a registry root.

use serde::{Deserialize, Serialize};

use super::error::ValidationResponse;
use super::jsjson::{self, LegacyValue};
use super::types::*;

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MerkleProof {
    pub proof: Vec<String>,
    #[serde(deserialize_with = "safe_integer_index")]
    pub index: u64,
    pub entity_hash: String,
    pub hashing_keys: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ThirdPartyProps {
    pub merkle_proof: MerkleProof,
    #[serde(default)]
    pub content: std::collections::HashMap<String, String>,
    pub id: String,
}

/// The largest integer a JSON number reader holds exactly (`Number.MAX_SAFE_INTEGER`).
const MAX_SAFE_INTEGER: u64 = (1 << 53) - 1;

/// A merkle index in any integral number form, up to `MAX_SAFE_INTEGER`: above
/// it the value the signer committed to is not recoverable from the JSON.
fn safe_integer_index<'de, D: serde::Deserializer<'de>>(d: D) -> Result<u64, D::Error> {
    let index = catalyst_shared::json_number::integral_u64(d)?;
    if index > MAX_SAFE_INTEGER {
        return Err(serde::de::Error::custom(format!(
            "merkle index {index} is above {MAX_SAFE_INTEGER}"
        )));
    }
    Ok(index)
}

pub const WEARABLE_REQUIRED_HASHING_KEYS: &[&str] = &["id", "content", "data"];

pub const EMOTE_REQUIRED_HASHING_KEYS: &[&str] = &["id", "content", "emoteDataADR74"];

pub fn validate_third_party_merkle_proof_content(
    deployment: &Deployment<'_>,
    required_hashing_keys: &[&str],
    item_label: &str,
) -> ValidationResponse {
    let entity = &deployment.entity;
    let metadata = match &entity.metadata {
        Some(m) => m,
        None => return ValidationResponse::Ok,
    };

    if metadata.get("merkleProof").is_none() {
        return ValidationResponse::Ok;
    }

    let tp_props: ThirdPartyProps = match serde_json::from_value(metadata.clone()) {
        Ok(p) => p,
        Err(e) => {
            return ValidationResponse::fail(format!("Failed to parse third-party metadata: {e}"));
        }
    };

    if entity.pointers.is_empty() || tp_props.id.to_lowercase() != entity.pointers[0].to_lowercase()
    {
        return ValidationResponse::fail(format!(
            "The id '{}' does not match the pointer '{}'",
            tp_props.id,
            entity.pointers.first().map(|s| s.as_str()).unwrap_or("")
        ));
    }

    if let Some(missing_key) = required_hashing_keys
        .iter()
        .find(|key| !tp_props.merkle_proof.hashing_keys.iter().any(|k| k == *key))
    {
        return ValidationResponse::fail(format!(
            "The third-party {item_label} merkle proof must commit the '{missing_key}' field"
        ));
    }

    let metadata_keys = match metadata_keys_in_property_order(deployment) {
        Ok(keys) => keys,
        Err(unavailable) => return unavailable,
    };
    if let Some(error) = full_commit_error(
        &metadata_keys,
        &tp_props.merkle_proof.hashing_keys,
        item_label,
    ) {
        return ValidationResponse::fail(error);
    }

    let all_content_in_files = tp_props.content.iter().all(|(file, hash)| {
        entity
            .content
            .iter()
            .any(|c| c.file == *file && c.hash == *hash)
    });

    let all_files_in_content = entity.content.iter().all(|c| {
        tp_props
            .content
            .get(&c.file)
            .map(|h| h == &c.hash)
            .unwrap_or(false)
    });

    if !all_content_in_files || !all_files_in_content {
        return ValidationResponse::fail(
            "The content declared in the metadata does not match the files uploaded with the entity"
                .to_string(),
        );
    }

    if tp_props.merkle_proof.entity_hash.is_empty() {
        return ValidationResponse::fail(
            "The entity hash in the merkle proof is empty".to_string(),
        );
    }

    let entity_bytes = match deployment
        .files
        .get(&entity.id)
        .and_then(UploadedFile::bytes)
    {
        Some(bytes) => bytes,
        None => return entity_bytes_missing(&entity.id),
    };

    let hashing_keys = &tp_props.merkle_proof.hashing_keys;
    let generated = match entity_hash_from_entity_bytes(entity_bytes, hashing_keys) {
        Some(hash) => hash,
        None => return entity_bytes_unparsable(&entity.id),
    };

    if !tp_props
        .merkle_proof
        .entity_hash
        .trim_start_matches("0x")
        .eq_ignore_ascii_case(&generated)
    {
        return ValidationResponse::fail(
            "The hash provided in the merkleProof doesn't match the one generated by the validator"
                .to_string(),
        );
    }

    if tp_props.merkle_proof.proof.is_empty() {
        return ValidationResponse::fail("The merkle proof is empty".to_string());
    }

    if tp_props.merkle_proof.hashing_keys.is_empty() {
        return ValidationResponse::fail(
            "The hashing keys in the merkle proof are empty".to_string(),
        );
    }

    ValidationResponse::Ok
}

/// `hashingKeys` must be exactly the metadata's top-level fields other than
/// `merkleProof`, each listed once, so the leaf commits every served field.
/// Checked in the reference's order: a repeated key, then an uncommitted
/// field, then a key that is not a field.
fn full_commit_error(
    metadata_keys: &[String],
    hashing_keys: &[String],
    item_label: &str,
) -> Option<String> {
    let mut seen = std::collections::HashSet::new();
    if let Some(duplicate) = hashing_keys.iter().find(|key| !seen.insert(key.as_str())) {
        return Some(format!(
            "The third-party {item_label} merkle proof lists '{duplicate}' more than once in hashingKeys"
        ));
    }

    let metadata_keys: Vec<&str> = metadata_keys
        .iter()
        .map(String::as_str)
        .filter(|key| *key != "merkleProof")
        .collect();

    if let Some(uncommitted) = metadata_keys.iter().find(|key| !seen.contains(*key)) {
        return Some(format!(
            "The third-party {item_label} merkle proof must commit every metadata field; \
             '{uncommitted}' is not in hashingKeys"
        ));
    }

    if let Some(unknown) = hashing_keys
        .iter()
        .find(|key| !metadata_keys.contains(&key.as_str()))
    {
        return Some(format!(
            "The third-party {item_label} merkle proof commits '{unknown}', which is not a metadata field"
        ));
    }

    None
}

/// The metadata's top-level keys as `Object.keys` lists them after `JSON.parse`
/// of the uploaded entity bytes, so the first uncommitted field reported is the
/// reference's. Without readable bytes the decision is deferred, as in the hash step.
fn metadata_keys_in_property_order(
    deployment: &Deployment<'_>,
) -> Result<Vec<String>, ValidationResponse> {
    let entity_id = &deployment.entity.id;
    let bytes = deployment
        .files
        .get(entity_id)
        .and_then(UploadedFile::bytes)
        .ok_or_else(|| entity_bytes_missing(entity_id))?;
    serde_json::from_slice::<LegacyValue>(bytes)
        .ok()
        .and_then(|root| {
            let entries = root.get("metadata")?.as_object()?;
            let keys = jsjson::property_order(entries.iter().map(|(k, _)| k.as_str()), |k| k);
            Some(keys.into_iter().map(str::to_owned).collect())
        })
        .ok_or_else(|| entity_bytes_unparsable(entity_id))
}

fn entity_bytes_missing(entity_id: &str) -> ValidationResponse {
    ValidationResponse::unavailable(format!(
        "The entity file bytes for '{entity_id}' were not available to recompute the third-party \
         merkle proof hash, so the deployment could not be validated. Please retry."
    ))
}

fn entity_bytes_unparsable(entity_id: &str) -> ValidationResponse {
    ValidationResponse::unavailable(format!(
        "The entity file bytes for '{entity_id}' could not be parsed to recompute the third-party \
         merkle proof hash, so the deployment could not be validated. Please retry."
    ))
}

pub fn verify_third_party_merkle_proof(proof: &MerkleProof, root: &[u8; 32]) -> bool {
    let decoded: Option<Vec<[u8; 32]>> = proof
        .proof
        .iter()
        .map(|p| super::merkle::decode_hash32(p))
        .collect();
    let Some(decoded) = decoded else {
        return false;
    };
    super::merkle::verify_proof(proof.index, &proof.entity_hash, &decoded, root)
}

/// `keccak256(JSON.stringify(pick(entity.metadata, hashingKeys)))` of the
/// reference (`@dcl/hashing`), from the raw uploaded entity JSON: `pick` keeps
/// each present key once, in `hashingKeys` order, and `JSON.stringify` writes
/// it in JS property order. `None` when the bytes are not valid JSON or carry
/// no `metadata` object.
fn entity_hash_from_entity_bytes(entity_bytes: &[u8], hashing_keys: &[String]) -> Option<String> {
    let root: LegacyValue = serde_json::from_slice(entity_bytes).ok()?;
    let metadata = root.get("metadata")?.as_object()?;
    let mut picked: Vec<(&str, &LegacyValue)> = Vec::new();
    for key in hashing_keys {
        if picked.iter().any(|(k, _)| k == key) {
            continue;
        }
        if let Some((k, value)) = metadata.iter().find(|(k, _)| k == key) {
            picked.push((k, value));
        }
    }
    let mut serialized = String::new();
    jsjson::write_object(picked, &mut serialized);
    Some(hex::encode(alloy_primitives::keccak256(
        serialized.as_bytes(),
    )))
}

pub fn get_third_party_id(urn: &str) -> Option<String> {
    let parts: Vec<&str> = urn.split(':').collect();
    if parts.len() >= 5 && parts[3].starts_with("collections-thirdparty") {
        Some(parts[..5].join(":"))
    } else {
        None
    }
}

pub fn hex_to_bytes(value: &str) -> Option<Vec<u8>> {
    crate::auth::decode_hex_0x(value).ok()
}

