#!/usr/bin/env python3
"""The git dependencies of the Explorer, as data and as a Cargo patch config.

Reads rendering/bevy-explorer/source/Cargo.lock and writes
  rendering/bevy-explorer/forks.toml          every git source: repo, branch, locked revision,
                                              the crates it supplies, upstream's stated reason,
                                              and (with --check-upstream) the parent repository
                                              and how far the fork has moved
  rendering/bevy-explorer/cargo-patches.toml  a Cargo config whose [patch."<git url>"] tables pin
                                              each crate to that revision; pass it with
                                              `cargo --config` to build the Explorer from a
                                              regenerated lock or point a fork at a mirror
"""
import argparse
import datetime
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.parse

ROOT = Path(__file__).resolve().parents[1]
PIN = ROOT / 'rendering/bevy-explorer'
SOURCE = PIN / 'source'
FORKS = PIN / 'forks.toml'
PATCHES = PIN / 'cargo-patches.toml'


def parse_git_sources(cargo_lock_text):
    """{(url, reference, rev): [(crate, version), ...]} from every git-sourced [[package]]."""
    sources = {}
    for block in cargo_lock_text.split('[[package]]')[1:]:
        fields = dict(re.findall(r'^(\w+) = "([^"]*)"$', block, re.M))
        source = fields.get('source', '')
        if not source.startswith('git+'):
            continue
        url, _, rev = source[4:].partition('#')
        url, _, query = url.partition('?')
        # The reference the manifest named: `branch=x`, `tag=x`, `rev=x`, or '' for the default
        # branch. Only `rev=` is exact already; the others are what the pin freezes.
        params = dict(urllib.parse.parse_qsl(query))
        reference = next((f'{k}={params[k]}' for k in ('branch', 'tag', 'rev') if k in params), '')
        sources.setdefault((url, reference, rev), []).append((fields['name'], fields['version']))
    return {key: sorted(crates) for key, crates in sources.items()}


def harvest_reasons(manifest_text, urls):
    """The `#` comment block right above the first manifest line naming each git url."""
    lines = manifest_text.splitlines()
    reasons = {}
    for url in urls:
        for index, line in enumerate(lines):
            # the url followed by its closing quote: robtfm/bevy must not match robtfm/bevy-console
            if (url + '"') not in line or line.lstrip().startswith('#'):
                continue
            comments = []
            cursor = index - 1
            while cursor >= 0 and lines[cursor].lstrip().startswith('#'):
                comments.insert(0, lines[cursor].lstrip('# ').rstrip())
                cursor -= 1
            if comments:
                reasons[url] = ' '.join(comments)
            break
    return reasons


def github_repo(url):
    match = re.fullmatch(r'https://github\.com/([^/]+)/([^/]+?)(?:\.git)?', url)
    return match.groups() if match else None


def gh_api(path):
    result = subprocess.run(['gh', 'api', path], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f'gh api {path}: {result.stderr.strip()}')
    return json.loads(result.stdout)


def check_upstream(url, reference, rev, api=gh_api):
    """Parent repository, the fork branch's distance from the parent's default branch, and the
    commits the fork branch gained since the pinned revision."""
    repo = github_repo(url)
    if repo is None:
        return {}
    owner, name = repo
    info = api(f'repos/{owner}/{name}')
    out = {'default_branch': info['default_branch'], 'pushed_at': info['pushed_at'][:10]}
    if info.get('fork') and info.get('parent'):
        parent = info['parent']['full_name']
        out['parent'] = parent
        compare = api(f'repos/{owner}/{name}/compare/{parent.split("/")[0]}:{info["parent"]["default_branch"]}...{rev}')
        out['ahead_of_parent'] = compare['ahead_by']
        out['behind_parent'] = compare['behind_by']
    kind, _, name_ref = reference.partition('=')
    if kind in ('branch', 'tag'):
        moved = api(f'repos/{owner}/{name}/compare/{rev}...{urllib.parse.quote(name_ref, safe="")}')
        out['branch_commits_since_pin'] = moved['ahead_by']
    return out


def toml_string(value):
    return json.dumps(value)


def render_forks(sources, reasons, upstream, checked):
    lines = ['# The git dependencies of the Explorer, generated by tooling/upstream-forks.py.',
             '# Do not edit: rerun the script when source/Cargo.lock changes.', '']
    if checked:
        lines.append(f'checked_upstream = {toml_string(checked)}')
    for (url, reference, rev), crates in sorted(sources.items()):
        lines += ['', '[[source]]', f'url = {toml_string(url)}']
        kind, _, name_ref = reference.partition('=')
        if kind in ('branch', 'tag'):
            lines.append(f'{kind} = {toml_string(name_ref)}')
        elif kind == 'rev':
            lines.append(f'manifest_rev = {toml_string(name_ref)}')
        lines.append(f'rev = {toml_string(rev)}')
        extra = upstream.get((url, reference, rev), {})
        for key in ('parent', 'default_branch', 'pushed_at', 'ahead_of_parent', 'behind_parent', 'branch_commits_since_pin'):
            if key in extra:
                value = extra[key]
                lines.append(f'{key} = {toml_string(value) if isinstance(value, str) else value}')
        if 'config_pin' in extra:
            lines.append(f'config_pin = {"true" if extra["config_pin"] else "false"}')
        if url in reasons:
            lines.append(f'reason = {toml_string(reasons[url])}')
        lines.append('crates = [')
        lines += [f'  {toml_string(f"{name} {version}")},' for name, version in crates]
        lines.append(']')
    return '\n'.join(lines) + '\n'


def manifest_crates_io_patches(manifest_text):
    """{crate: git url} for the manifest's [patch.crates-io] entries that point at a git source."""
    table = tomllib.loads(manifest_text).get('patch', {}).get('crates-io', {})
    return {name: spec['git'] for name, spec in table.items() if isinstance(spec, dict) and 'git' in spec}


def splitting_sources(metadata):
    """Git repositories that `cargo metadata` resolved under two source forms (branch and rev):
    a config pin on such a repository duplicates its crates instead of pinning them."""
    forms = {}
    for package in metadata['packages']:
        source = package.get('source') or ''
        if not source.startswith('git+'):
            continue
        url = source[4:].split('?')[0].split('#')[0]
        forms.setdefault(url, set()).add(source.split('#')[0])
    return {url for url, seen in forms.items() if len(seen) > 1}


def revision_drift(metadata, sources):
    """{url: (pinned, resolved)} for git packages the config resolved to another revision than
    the pinned lock; empty when the config reproduces the lock's revisions."""
    pinned = {url: rev for (url, _, rev) in sources}
    drift = {}
    for package in metadata['packages']:
        source = package.get('source') or ''
        if not source.startswith('git+') or '#' not in source:
            continue
        url = source[4:].split('?')[0].split('#')[0]
        resolved = source.rsplit('#', 1)[1]
        if url in pinned and pinned[url] != resolved:
            drift[url] = (pinned[url], resolved)
    return drift


def verify_patches(source_dir, patches_text, locked=False):
    """Resolve the pinned workspace with the config applied, on a copy of its lock; returns the
    metadata (or raises with cargo's message)."""
    lock_path = source_dir / 'Cargo.lock'
    backup = lock_path.read_bytes()
    with tempfile.NamedTemporaryFile('w', suffix='.toml', delete=False) as handle:
        handle.write(patches_text)
        config = handle.name
    try:
        command = ['cargo', '--config', config, 'metadata', '--manifest-path', str(source_dir / 'Cargo.toml'), '--format-version', '1']
        if locked:
            command.insert(3, '--locked')
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            raise RuntimeError(result.stderr.strip().splitlines()[-1] if result.stderr.strip() else 'cargo metadata failed')
        return json.loads(result.stdout)
    finally:
        lock_path.write_bytes(backup)
        Path(config).unlink(missing_ok=True)


def render_patches(sources, patched, splitting=()):
    """A Cargo config: [patch.crates-io] pins every crate upstream patches from crates.io onto a
    fork to the revision the lock resolved (a config patch overrides the manifest's branch form;
    the regenerated lock keeps the revisions and records them in rev form); the forks the
    manifests name directly as git dependencies can only be patched onto a DIFFERENT source, so
    they are written as a mirror template."""
    by_url = {}
    for (url, reference, rev), crates in sources.items():
        by_url[url] = (reference, rev, crates)
    lines = ['# Cargo config for building the Explorer source (generated by',
             '# tooling/upstream-forks.py from its Cargo.lock):',
             '#   cargo --config /path/to/cargo-patches.toml build ...',
             '#',
             '# [patch.crates-io] pins each crate upstream patches onto a fork to the exact revision the',
             '# lock resolved, so a regenerated lock cannot drift along the fork branch. The forks the',
             '# manifests depend on directly are the commented template below: cargo only accepts a',
             '# patch that names a different source, so fill in a mirror url and uncomment to take',
             '# that fork from somewhere other than its author\'s repository.', '', '[patch.crates-io]']
    for url in sorted({u for u in patched.values()}):
        if url not in by_url:
            continue
        reference, rev, crates = by_url[url]
        kind, _, name_ref = reference.partition('=')
        names = sorted(n for n, u in patched.items() if u == url)
        if url in splitting:
            lines += [f'# {url} ({kind} {name_ref}): NOT pinned here. Another dependency names this repository',
                      '# by branch directly, so a config pin resolves it twice (branch and rev copies of every',
                      '# crate); the lock alone holds its revision. Pin it through a mirror below instead.']
            lines += [f'# {name} = {{ git = {toml_string(url)}, rev = {toml_string(rev)} }}' for name in names]
            continue
        lines.append(f'# {url} ({kind} {name_ref})' if kind else f'# {url} (default branch)')
        for name in names:
            lines.append(f'{name} = {{ git = {toml_string(url)}, rev = {toml_string(rev)} }}')
    direct = sorted((set(by_url) - set(patched.values())) | (set(splitting) & set(by_url)))
    if direct:
        lines += ['', '# Direct git dependencies: mirror template (replace MIRROR_URL, then uncomment).']
    for url in direct:
        reference, rev, crates = by_url[url]
        kind, _, name_ref = reference.partition('=')
        lines += ['', f'# [patch.{toml_string(url)}]  # {kind} {name_ref}' if kind else f'# [patch.{toml_string(url)}]  # default branch']
        for name, _version in crates:
            lines.append(f'# {name} = {{ git = "MIRROR_URL", rev = {toml_string(rev)} }}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check-upstream', action='store_true', help='ask GitHub for each fork\'s parent and distance (needs gh)')
    parser.add_argument('--verify', action='store_true', help='resolve the pinned workspace with the config (needs cargo and the imported source); records which sources a config pin would split')
    parser.add_argument('--check', action='store_true', help='fail when the written files differ from the pinned lock')
    args = parser.parse_args()
    source_dir = SOURCE
    cargo_lock = source_dir / 'Cargo.lock'
    if not cargo_lock.exists():
        raise SystemExit(f'{cargo_lock} is missing')
    sources = parse_git_sources(cargo_lock.read_text())
    manifests = [source_dir / 'Cargo.toml', *sorted((source_dir / 'crates').glob('*/Cargo.toml'))]
    reasons = harvest_reasons('\n'.join(m.read_text() for m in manifests if m.exists()), {url for url, _, _ in sources})
    upstream, checked = {}, None
    if args.check_upstream:
        checked = datetime.date.today().isoformat()
        for key in sources:
            upstream[key] = check_upstream(*key)
    elif FORKS.exists():
        # keep the last upstream check so a lock-only rerun does not drop it
        previous = tomllib.loads(FORKS.read_text())
        checked = previous.get('checked_upstream')
        for entry in previous.get('source', []):
            reference = next((f'{k}={entry[k]}' for k in ('branch', 'tag') if k in entry), '')
            if 'manifest_rev' in entry:
                reference = f'rev={entry["manifest_rev"]}'
            key = (entry['url'], reference, entry['rev'])
            upstream[key] = {k: entry[k] for k in ('parent', 'default_branch', 'pushed_at', 'ahead_of_parent', 'behind_parent', 'branch_commits_since_pin', 'config_pin') if k in entry}
    patched = manifest_crates_io_patches((source_dir / 'Cargo.toml').read_text())
    pinnable_urls = set(patched.values()) & {url for url, _, _ in sources}
    splitting = {url for (url, _, _), extra in upstream.items() if extra.get('config_pin') is False}
    if args.verify:
        # Two resolutions on a copy of the lock: the first finds the repositories a config pin
        # resolves twice, the second proves the rest reproduces the lock's revisions. A config
        # pin rewrites the lock's source lines from branch to rev form, so --locked cannot pass.
        splitting = splitting_sources(verify_patches(source_dir, render_patches(sources, patched, splitting)))
        metadata = verify_patches(source_dir, render_patches(sources, patched, splitting))
        remaining = splitting_sources(metadata)
        if remaining:
            raise SystemExit('still resolved twice after excluding the splitting sources: ' + ', '.join(sorted(remaining)))
        drift = revision_drift(metadata, sources)
        if drift:
            raise SystemExit('the config resolves other revisions than the lock: ' + ', '.join(f'{u} {a[:8]}->{b[:8]}' for u, (a, b) in sorted(drift.items())))
        print(f'verified: the config reproduces the lock\'s revisions; {len(pinnable_urls - splitting)} source(s) pinned, {len(splitting)} left to the lock')
    if args.verify or splitting:
        for key in sources:
            if key[0] in pinnable_urls:
                upstream.setdefault(key, {})['config_pin'] = key[0] not in splitting
    forks = render_forks(sources, reasons, upstream, checked)
    patches = render_patches(sources, patched, splitting)
    if args.check:
        stale = [p for p, text in ((FORKS, forks), (PATCHES, patches)) if not p.exists() or p.read_text() != text]
        if stale:
            raise SystemExit('stale: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale) + '; run python3 tooling/upstream-forks.py')
        print('forks.toml and cargo-patches.toml match the pinned lock')
        return 0
    FORKS.write_text(forks)
    PATCHES.write_text(patches)
    print(f'{len(sources)} git sources, {sum(len(c) for c in sources.values())} crates -> {FORKS.relative_to(ROOT)}, {PATCHES.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
