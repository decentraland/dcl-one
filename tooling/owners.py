#!/usr/bin/env python3
"""Render GitHub CODEOWNERS from the service/domain ownership catalogue."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def render():
    catalog = json.loads((ROOT / 'ownership.json').read_text(encoding='utf-8'))
    lines = ['# Generated by python3 tooling/owners.py from ownership.json.',
             '# Empty owner lists are deliberately unassigned; commented rules do not request reviews.',
             '# Assign real GitHub teams/users, regenerate, then enable required owner reviews.', '']
    missing = []
    for area in catalog['areas']:
        owners = area['owners']
        for owner in owners:
            if not re.fullmatch(r'@[A-Za-z0-9-]+(?:/[A-Za-z0-9_-]+)?', owner):
                raise ValueError(f'Invalid GitHub owner in {area["id"]}: {owner}')
        lines.append('# ' + area['id'])
        if not owners:
            missing.append(area['id'])
        for pattern in area['paths']:
            if pattern != '*' and not pattern.startswith('/'):
                raise ValueError('Ownership paths must be anchored at the repository root')
            lines.append(pattern + ' ' + ' '.join(owners) if owners else '# UNASSIGNED ' + pattern)
        lines.append('')
    return '\n'.join(lines), missing


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--require-owners', action='store_true')
    args = parser.parse_args()
    rendered, missing = render()
    target = ROOT / '.github/CODEOWNERS'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != rendered:
            raise SystemExit('CODEOWNERS is stale; run python3 tooling/owners.py')
    else:
        target.parent.mkdir(exist_ok=True)
        target.write_text(rendered, encoding='utf-8')
    if args.require_owners and missing:
        raise SystemExit('Unassigned ownership areas: ' + ', '.join(missing))
    print(f'CODEOWNERS matches the catalogue; {len(missing)} areas await team assignment.')


if __name__ == '__main__':
    main()
