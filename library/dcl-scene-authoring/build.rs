use std::io::Result;
use std::path::{Path, PathBuf};

/// The vendored @dcl/protocol protos become the static schema table
/// src/crdt_gen.rs serializes composite JSON with, without node or
/// @dcl/inspector. Host-side only: the table is plain Rust, so the crate
/// itself needs no protobuf runtime on any target.
fn main() -> Result<()> {
    println!("cargo:rerun-if-changed=proto");
    generate_component_schema()
}

fn protox_error(e: protox::Error) -> std::io::Error {
    std::io::Error::other(format!("{e:?}"))
}

/// The vendored protos carry a UTF-8 BOM, which protoc skips and protox's
/// lexer refuses; this resolver drops it before parsing.
struct BomTolerant {
    include: PathBuf,
    inner: protox::file::IncludeFileResolver,
}

impl protox::file::FileResolver for BomTolerant {
    fn resolve_path(&self, path: &Path) -> Option<String> {
        self.inner.resolve_path(path)
    }

    fn open_file(&self, name: &str) -> std::result::Result<protox::file::File, protox::Error> {
        let path = self.include.join(name);
        if !path.is_file() {
            return Err(protox::Error::file_not_found(name));
        }
        let source = std::fs::read_to_string(&path)?;
        protox::file::File::from_source(name, source.strip_prefix('\u{feff}').unwrap_or(&source))
    }
}

/// What `protoc --include_imports -o` produced, without protoc.
fn compile_protos(files: &[PathBuf], include: &Path) -> Result<prost_types::FileDescriptorSet> {
    let mut resolver = protox::file::ChainFileResolver::new();
    resolver.add(BomTolerant {
        include: include.to_path_buf(),
        inner: protox::file::IncludeFileResolver::new(include.to_path_buf()),
    });
    resolver.add(protox::file::GoogleFileResolver::new());
    let mut compiler = protox::Compiler::with_file_resolver(resolver);
    compiler.include_imports(true);
    compiler.open_files(files).map_err(protox_error)?;
    Ok(compiler.file_descriptor_set())
}

fn generate_component_schema() -> Result<()> {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let comp_dir = Path::new("proto/decentraland/sdk/components");
    let mut protos: Vec<PathBuf> = std::fs::read_dir(comp_dir)?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|e| e.to_str()) == Some("proto"))
        .collect();
    protos.sort();

    let fds = compile_protos(&protos, Path::new("proto"))?;

    let mut msg_index: Vec<(String, prost_types::DescriptorProto)> = Vec::new();
    let mut enum_index: Vec<(String, prost_types::EnumDescriptorProto)> = Vec::new();
    for file in &fds.file {
        let pkg = file.package();
        for m in &file.message_type {
            collect_messages(pkg, m, &mut msg_index, &mut enum_index);
        }
        for e in &file.enum_type {
            enum_index.push((format!("{pkg}.{}", e.name()), e.clone()));
        }
    }
    let msg_pos = |full: &str| msg_index.iter().position(|(n, _)| n == full);
    let enum_pos = |full: &str| enum_index.iter().position(|(n, _)| n == full);

    let mut src =
        String::from("// @generated by build.rs from proto/decentraland/sdk/components\n");
    src.push_str("pub(crate) static MESSAGES: &[MsgDef] = &[\n");
    for (full, m) in &msg_index {
        let map_entry = m.options.as_ref().is_some_and(|o| o.map_entry());
        let mut fields: Vec<&prost_types::FieldDescriptorProto> = m.field.iter().collect();
        fields.sort_by_key(|f| f.number());
        src.push_str(&format!(
            "    MsgDef {{ name: {full:?}, map_entry: {map_entry}, fields: &[\n"
        ));
        for f in fields {
            use prost_types::field_descriptor_proto::{Label, Type};
            let repeated = f.label() == Label::Repeated;
            let optional = f.proto3_optional();
            let strip = |s: &str| s.trim_start_matches('.').to_string();
            let kind = match f.r#type() {
                Type::Double => "FieldKind::Double".into(),
                Type::Float => "FieldKind::Float".into(),
                Type::Int32 => "FieldKind::Int32".into(),
                Type::Int64 => "FieldKind::Int64".into(),
                Type::Uint32 => "FieldKind::Uint32".into(),
                Type::Uint64 => "FieldKind::Uint64".into(),
                ty @ (Type::Sint32
                | Type::Sint64
                | Type::Fixed32
                | Type::Fixed64
                | Type::Sfixed32
                | Type::Sfixed64) => {
                    panic!("{}.{}: {ty:?} fields are not supported", full, f.name())
                }
                Type::Bool => "FieldKind::Bool".into(),
                Type::String => "FieldKind::Str".into(),
                Type::Bytes => "FieldKind::Bytes".into(),
                Type::Enum => {
                    let full = strip(f.type_name());
                    let idx = enum_pos(&full)
                        .unwrap_or_else(|| panic!("enum {full} not found in descriptor set"));
                    format!("FieldKind::Enum({idx})")
                }
                Type::Message | Type::Group => {
                    let full = strip(f.type_name());
                    let idx = msg_pos(&full)
                        .unwrap_or_else(|| panic!("message {full} not found in descriptor set"));
                    format!("FieldKind::Msg({idx})")
                }
            };
            let packable = !matches!(
                f.r#type(),
                Type::String | Type::Bytes | Type::Message | Type::Group
            );
            let packed =
                repeated && packable && f.options.as_ref().and_then(|o| o.packed) != Some(false);
            let oneof = match f.oneof_index {
                Some(i) if !optional => {
                    let name = m.oneof_decl[i as usize].name();
                    format!("Some({:?})", camel_case(name))
                }
                _ => "None".to_string(),
            };
            src.push_str(&format!(
                "        FieldDef {{ number: {}, json_name: {:?}, kind: {kind}, repeated: {repeated}, packed: {packed}, optional: {optional}, oneof: {oneof} }},\n",
                f.number(),
                f.json_name(),
            ));
        }
        src.push_str("    ] },\n");
    }
    src.push_str("];\n");

    src.push_str("pub(crate) static ENUMS: &[EnumDef] = &[\n");
    for (_, e) in &enum_index {
        let values: Vec<String> = e
            .value
            .iter()
            .map(|v| format!("({:?}, {})", v.name(), v.number()))
            .collect();
        src.push_str(&format!(
            "    EnumDef {{ values: &[{}] }},\n",
            values.join(", ")
        ));
    }
    src.push_str("];\n");

    src.push_str("pub(crate) static COMPONENTS: &[ComponentDef] = &[\n");
    for proto in &protos {
        let text = std::fs::read_to_string(proto)?;
        let Some(id) = parse_ecs_component_id(&text) else {
            println!(
                "cargo:warning=no ecs_component_id in {}; skipping",
                proto.display()
            );
            continue;
        };
        let stem = proto.file_stem().unwrap().to_string_lossy();
        let pascal = pascal_case(&stem);
        let full = format!("decentraland.sdk.components.PB{pascal}");
        let Some(idx) = msg_pos(&full) else {
            println!("cargo:warning=message {full} not found; skipping component");
            continue;
        };
        src.push_str(&format!(
            "    ComponentDef {{ name: \"core::{pascal}\", id: {id}, msg: {idx} }},\n"
        ));
    }
    src.push_str("];\n");

    std::fs::write(out_dir.join("components_schema.rs"), src)
}

fn collect_messages(
    prefix: &str,
    m: &prost_types::DescriptorProto,
    msgs: &mut Vec<(String, prost_types::DescriptorProto)>,
    enums: &mut Vec<(String, prost_types::EnumDescriptorProto)>,
) {
    let full = format!("{prefix}.{}", m.name());
    msgs.push((full.clone(), m.clone()));
    for e in &m.enum_type {
        enums.push((format!("{full}.{}", e.name()), e.clone()));
    }
    for nested in &m.nested_type {
        collect_messages(&full, nested, msgs, enums);
    }
}

fn parse_ecs_component_id(proto_text: &str) -> Option<u32> {
    let idx = proto_text.find("ecs_component_id")?;
    let rest = &proto_text[idx..];
    let eq = rest.find('=')?;
    let digits: String = rest[eq + 1..]
        .trim_start()
        .chars()
        .take_while(|c| c.is_ascii_digit())
        .collect();
    digits.parse().ok()
}

fn pascal_case(snake: &str) -> String {
    snake
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn camel_case(snake: &str) -> String {
    let pascal = pascal_case(snake);
    let mut c = pascal.chars();
    match c.next() {
        Some(f) => f.to_lowercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}
