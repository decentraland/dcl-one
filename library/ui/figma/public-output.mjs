import { Buffer } from 'node:buffer'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { lstatSync, readFileSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { handWrittenComponentDirectories } from './component-generation.mjs'
import { scanBuffer } from './key-guard.mjs'

const POINTER = Buffer.from('version https://git-lfs.github.com/spec/v1')
const DIGEST = /^[0-9a-f]{64}$/
const MODES = new Set(['100644', '100755'])
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const isPointer = (bytes) => bytes.subarray(0, POINTER.length).equals(POINTER)

function portable(value) {
  return (
    typeof value === 'string' &&
    value.length > 0 &&
    !value.startsWith('/') &&
    !/[\\<>:"|?*]/.test(value) &&
    ![...value].some(
      (character) => character.charCodeAt(0) < 32 || character.charCodeAt(0) === 127
    ) &&
    value
      .split('/')
      .every(
        (part) =>
          part &&
          part !== '.' &&
          part !== '..' &&
          !/[. ]$/.test(part) &&
          !/^(?:con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(part)
      )
  )
}

function inspectPath(root, relative) {
  let current = root
  const parts = relative.split('/')
  for (let index = 0; index < parts.length; index++) {
    current = path.join(current, parts[index])
    const stat = lstatSync(current, { throwIfNoEntry: false })
    if (!stat) return 'missing'
    if (stat.isSymbolicLink()) return 'symlink'
    if (index < parts.length - 1 ? !stat.isDirectory() : !stat.isFile()) return 'special file'
  }
  return undefined
}

function filesUnder(directory, problems, prefix = '') {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name
    if (!portable(relative)) problems.push('unsafe public file path: ' + relative)
    else if (entry.isSymbolicLink()) problems.push('public output contains a symlink: ' + relative)
    else if (entry.isDirectory())
      files.push(...filesUnder(path.join(directory, entry.name), problems, relative + '/'))
    else if (!entry.isFile()) problems.push('public output contains a special file: ' + relative)
    else files.push(relative)
  }
  return files
}

function indexFiles(root, paths) {
  const listing = execFileSync(
    'git',
    [
      '--no-replace-objects',
      '--literal-pathspecs',
      '-C',
      root,
      'ls-files',
      '-s',
      '-z',
      '--',
      ...paths
    ],
    { maxBuffer: 1 << 28 }
  )
  const entries = new Map()
  for (const line of listing.toString('utf8').split('\0').filter(Boolean)) {
    const tab = line.indexOf('\t')
    const [mode, oid, stage] = line.slice(0, tab).split(' ')
    const file = line.slice(tab + 1)
    const previous = entries.get(file)
    entries.set(file, { mode, oid, unmerged: stage !== '0' || Boolean(previous) })
  }
  return entries
}

function indexBlobs(root, entries) {
  const ids = [
    ...new Set(
      [...entries.values()]
        .filter((entry) => !entry.unmerged && MODES.has(entry.mode))
        .map((entry) => entry.oid)
    )
  ]
  if (!ids.length) return new Map()
  const output = execFileSync('git', ['--no-replace-objects', '-C', root, 'cat-file', '--batch'], {
    input: ids.join('\n') + '\n',
    maxBuffer: 1 << 30
  })
  const blobs = new Map()
  let offset = 0
  for (const oid of ids) {
    const end = output.indexOf(0x0a, offset)
    const [found, kind, size] = output.subarray(offset, end).toString('utf8').split(' ')
    if (end < 0 || found !== oid || kind !== 'blob' || !/^\d+$/.test(size))
      throw new Error('invalid index blob')
    const start = end + 1
    const finish = start + Number(size)
    if (finish >= output.length || output[finish] !== 0x0a) throw new Error('truncated index blob')
    blobs.set(oid, output.subarray(start, finish))
    offset = finish + 1
  }
  return blobs
}

// A Figma file key's shape: 22 letters and digits, mixing upper case, lower case and digits.
const KEY_SHAPE =
  /(?<![A-Za-z0-9])(?=[A-Za-z0-9]{0,21}[0-9])(?=[A-Za-z0-9]{0,21}[a-z])(?=[A-Za-z0-9]{0,21}[A-Z])[A-Za-z0-9]{22}(?![A-Za-z0-9])/
// Known generator markers: the generator's header, any import of the generated runtime it renders through, the
// generated mapping header and captured Figma node identities in the generator's comment form.
const GENERATED_MARKERS = [
  /Generated by dcl-figma/,
  /['"](?:\.{1,2}\/)+(?:\.\.\/)*runtime(?:\/|['"])/,
  /runtime\/figma-(?:module-runtime|view-state|interactions)\b/,
  /\bregisterComponent\s*\(/,
  /\bFigmaView\b/,
  /^\/\/ Figma: .*\(\d+:\d+\)/m,
  /^\/\/ source=components\/[^\n]*\n\/\/ component=/m
]
const HAND_WRITTEN_NAME = /^[A-Z][A-Za-z0-9]*$/
const HAND_WRITTEN_FILE = /\.(?:tsx|ts|css)$/

/**
 * Hand-written components are plain tracked source that no installer writes and the lock never pins. They are still
 * refused when they are not committed as plain Git blobs or carry what belongs to the generated or captured output.
 */
function handWrittenProblems(root, scope, directories, owned, files, index, blobs, problems) {
  const installed = new Set(
    owned
      .filter((file) => file.includes('/'))
      .map((file) => file.split('/')[0].normalize('NFC').toLowerCase())
  )
  for (const directory of directories) {
    if (!HAND_WRITTEN_NAME.test(directory))
      problems.push('unsafe hand-written component directory: ' + directory)
    if (installed.has(directory.normalize('NFC').toLowerCase()))
      problems.push('hand-written component collides with an installed component: ' + directory)
  }
  const key = process.env.FIGMA_FILE_KEY || undefined
  for (const file of files) {
    const label = 'hand-written component file: ' + file
    if (!HAND_WRITTEN_FILE.test(file)) {
      problems.push('unsupported ' + label)
      continue
    }
    const indexed = index.get(scope + '/' + file)
    if (!indexed) {
      problems.push('untracked ' + label)
      continue
    }
    if (indexed.unmerged || !MODES.has(indexed.mode)) {
      problems.push('unsafe index entry for ' + label)
      continue
    }
    const unsafe = inspectPath(root, scope + '/' + file)
    if (unsafe) {
      problems.push(unsafe + ' ' + label)
      continue
    }
    const bytes = readFileSync(path.join(root, scope, file))
    const blob = blobs.get(indexed.oid)
    if (isPointer(bytes) || isPointer(blob)) {
      problems.push('LFS pointer in ' + label)
      continue
    }
    if (!blob.equals(bytes)) problems.push('index bytes differ for ' + label)
    const text = bytes.toString('utf8')
    if (scanBuffer(bytes, key).length || KEY_SHAPE.test(text))
      problems.push('Figma file key or URL in ' + label)
    if (GENERATED_MARKERS.some((marker) => marker.test(text)))
      problems.push('generated or captured output in ' + label)
  }
}

function componentImplementations(root, problems) {
  const prefix = 'library/ui/figma'
  const executable = (name) =>
    /\.(?:[cm]?[jt]sx?)$/i.test(name) && !/\.(?:test|spec)\.[^.]+$/i.test(name)
  const files = []
  const visit = (relative, recursive) => {
    const directory = path.join(root, relative)
    const stat = lstatSync(directory, { throwIfNoEntry: false })
    if (!stat) return false
    if (!stat.isDirectory() || stat.isSymbolicLink()) {
      problems.push('unsafe component implementation directory: ' + relative)
      return false
    }
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const file = relative + '/' + entry.name
      if (entry.isSymbolicLink()) {
        if (recursive || executable(entry.name))
          problems.push('symlink component implementation: ' + file)
      } else if (entry.isDirectory()) {
        if (recursive) visit(file, true)
        else if (executable(entry.name)) problems.push('unsafe component implementation: ' + file)
      } else if (executable(entry.name)) {
        if (entry.isFile()) files.push(file)
        else problems.push('unsafe component implementation: ' + file)
      }
    }
    return true
  }
  if (visit(prefix, false)) visit(prefix + '/src', true)
  return files
}

/** Resolver controls are checked independently of origin claims and executable-file exclusions. */
function componentResolverBoundary(root, inputFiles, problems) {
  const prefix = 'library/ui/figma'
  const executable = (file) => /\.(?:[cm]?[jt]sx?)$/i.test(file)
  const controls = (name) =>
    name.toLowerCase() === 'package.json' || /^(?:tsconfig|jsconfig)(?:\.[^/]*)?\.json$/i.test(name)
  const runtime = new Set(
    ['figma-module-runtime.tsx', 'figma-view-state.ts', 'figma-interactions.tsx'].map(
      (name) => prefix + '/review/src/components/' + name
    )
  )
  const checked = new Set()
  const inspect = (relative, recurse = false, helpers = false) => {
    const directory = path.join(root, relative)
    const stat = lstatSync(directory, { throwIfNoEntry: false })
    if (!stat) return
    if (stat.isSymbolicLink() || !stat.isDirectory()) {
      problems.push('unsafe component resolver directory: ' + relative)
      return
    }
    const first = !checked.has(relative)
    checked.add(relative)
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const file = relative + '/' + entry.name
      if (first && (controls(entry.name) || entry.name.toLowerCase() === 'node_modules')) {
        if (file !== prefix + '/tsconfig.json' || !inputFiles.has(file))
          problems.push('unexpected component resolver control: ' + file)
        else if (!entry.isFile() || entry.isSymbolicLink())
          problems.push('unsafe component resolver control: ' + file)
      }
      if (entry.name.toLowerCase() === 'node_modules') continue
      if (recurse && !entry.isFile() && !entry.isDirectory() && !entry.isSymbolicLink())
        problems.push('unsafe component resolver entry: ' + file)
      if (helpers && executable(entry.name) && !inputFiles.has(file))
        problems.push('unpinned component helper implementation: ' + file)
      if (recurse && entry.isDirectory() && !entry.isSymbolicLink()) inspect(file, true)
    }
  }
  inspect(prefix)
  inspect(prefix + '/src', true)
  for (const file of inputFiles.keys()) {
    if (
      !file.startsWith(prefix + '/') ||
      !executable(file) ||
      runtime.has(file) ||
      file.startsWith(prefix + '/src/') ||
      path.posix.dirname(file) === prefix
    )
      continue
    let directory = path.posix.dirname(file)
    while (directory.startsWith(prefix + '/')) {
      inspect(directory, false, true)
      directory = path.posix.dirname(directory)
    }
  }
}

/**
 * Inspect only independently supplied paths and pins. Origin claims never select filesystem inputs.
 * @param {string} root
 * @param {{scope: string, table: Record<string, {sha256: string, origin?: unknown}>, lfsFiles?: ReadonlySet<string>, inputFiles?: ReadonlyMap<string, {sha256: string}>}} options
 * Under library/ui/components, files in a top-level directory the table does not name are hand-written components:
 * they are checked as plain tracked source (handWrittenProblems), never as pinned outputs.
 * @returns {{problems: string[], outputs: Map<string, {sha256: string, indexBlobSha: string, origin: unknown}>, inputs: Map<string, {sha256: string, indexBlobSha: string}>, actual: string[], indexPaths: string[], handWritten: string[]}}
 */
export function inspectPublicOutput(
  root,
  { scope, table, lfsFiles = new Set(), inputFiles = new Map() }
) {
  const problems = []
  const outputs = new Map()
  const inputs = new Map()
  const result = { problems, outputs, inputs, actual: [], indexPaths: [], handWritten: [] }
  if (!['library/ui/foundations', 'library/ui/components'].includes(scope)) {
    problems.push('unsupported public output scope')
    return result
  }
  if (!table || typeof table !== 'object' || Array.isArray(table) || !Object.keys(table).length) {
    problems.push('public output has no pinned file table')
    return result
  }
  const expected = Object.keys(table).sort()
  const safeExpected = expected.filter((file) => {
    if (portable(file)) return true
    problems.push('unsafe public file path')
    return false
  })
  const allowedLfs = scope === 'library/ui/foundations' ? lfsFiles : new Set()
  if (scope === 'library/ui/components' && lfsFiles.size)
    problems.push('components do not permit LFS exceptions')
  for (const file of allowedLfs)
    if (
      !portable(file) ||
      !/^typography\/fonts\/[^/]+\.woff2$/.test(file) ||
      !Object.hasOwn(table, file)
    )
      problems.push('unsafe foundation LFS exception: ' + file)
  const safeInputs = []
  for (const [file, entry] of inputFiles) {
    if (!portable(file) || !DIGEST.test(entry?.sha256 ?? ''))
      problems.push('unsafe or unpinned public input: ' + file)
    else safeInputs.push(file)
  }
  try {
    // Check directory ancestors without traversing a symlink before listing any children.
    const rootStat = lstatSync(root, { throwIfNoEntry: false })
    if (!rootStat || rootStat.isSymbolicLink() || !rootStat.isDirectory()) {
      problems.push('public output directory is missing or unsafe')
      return result
    }
    let directory = root
    for (const part of scope.split('/')) {
      directory = path.join(directory, part)
      const stat = lstatSync(directory, { throwIfNoEntry: false })
      if (!stat || stat.isSymbolicLink() || !stat.isDirectory()) {
        problems.push('public output directory is missing or unsafe')
        return result
      }
    }
    result.actual = filesUnder(directory, problems).sort()
    const actual = new Set(result.actual)
    const collisions = new Set()
    for (const file of new Set([...expected, ...result.actual])) {
      const normalized = file.normalize('NFC').toLowerCase()
      if (collisions.has(normalized)) problems.push('non-portable public file collision: ' + file)
      collisions.add(normalized)
    }
    // Inventory executable source independently of a manifest's claimed input list.
    const sourceScope =
      scope === 'library/ui/components' && inputFiles.size ? ['library/ui/figma'] : []
    const index = indexFiles(root, [scope, ...safeInputs, ...sourceScope])
    result.indexPaths = [...index.keys()].sort()
    if (sourceScope.length) {
      for (const file of componentImplementations(root, problems))
        if (!index.has(file)) problems.push('untracked component implementation: ' + file)
    }
    const blobs = indexBlobs(root, index)
    const indexed = [...index.keys()]
      .filter((file) => file.startsWith(scope + '/'))
      .map((file) => file.slice(scope.length + 1))
    const handWritten = new Set(
      scope === 'library/ui/components'
        ? handWrittenComponentDirectories([...result.actual, ...indexed], expected)
        : []
    )
    const isHandWritten = (file) => file.includes('/') && handWritten.has(file.split('/')[0])
    for (const file of result.actual)
      if (!Object.hasOwn(table, file) && !isHandWritten(file))
        problems.push('extra public file: ' + file)
    for (const file of indexed)
      if (!Object.hasOwn(table, file) && !isHandWritten(file))
        problems.push('extra indexed public file: ' + file)
    result.handWritten = [...new Set([...result.actual, ...indexed])].filter(isHandWritten).sort()
    for (const file of result.handWritten)
      if (!actual.has(file)) problems.push('missing hand-written component file: ' + file)
    handWrittenProblems(
      root,
      scope,
      [...handWritten],
      expected,
      result.handWritten.filter((file) => actual.has(file)),
      index,
      blobs,
      problems
    )
    function identity(file, pin, label, lfs) {
      const indexed = index.get(file)
      if (!indexed) {
        problems.push('untracked ' + label)
        return undefined
      }
      if (indexed.unmerged) {
        problems.push('unmerged ' + label)
        return undefined
      }
      if (!MODES.has(indexed.mode)) {
        problems.push('unsafe index mode for ' + label)
        return undefined
      }
      const unsafe = inspectPath(root, file)
      if (unsafe) {
        problems.push(unsafe + ' ' + label)
        return undefined
      }
      const bytes = readFileSync(path.join(root, file))
      if (isPointer(bytes)) {
        problems.push('unmaterialized ' + label)
        return undefined
      }
      const digest = sha256(bytes)
      const blob = blobs.get(indexed.oid)
      let valid = true
      if (!DIGEST.test(pin ?? '') || digest !== pin) {
        problems.push('changed ' + label)
        valid = false
      }
      if (lfs) {
        const match =
          /^version https:\/\/git-lfs.github.com\/spec\/v1\noid sha256:([0-9a-f]{64})\nsize (0|[1-9][0-9]*)\n$/.exec(
            blob.toString('utf8')
          )
        if (
          !match ||
          match[1] !== pin ||
          match[1] !== digest ||
          match[2] !== String(bytes.length)
        ) {
          problems.push('font LFS identity mismatch: ' + file.slice(scope.length + 1))
          valid = false
        }
      } else if (isPointer(blob) || !blob.equals(bytes)) {
        problems.push(
          label.startsWith('public file: ')
            ? 'public index bytes differ: ' + label.slice('public file: '.length)
            : 'input index bytes differ: ' + file
        )
        valid = false
      }
      return valid ? { sha256: digest, indexBlobSha: indexed.oid } : undefined
    }
    for (const file of safeExpected) {
      if (!actual.has(file)) {
        problems.push('missing public file: ' + file)
        continue
      }
      const found = identity(
        scope + '/' + file,
        table[file]?.sha256,
        'public file: ' + file,
        allowedLfs.has(file)
      )
      if (found) outputs.set(file, { ...found, origin: table[file]?.origin })
    }
    for (const file of safeInputs) {
      const found = identity(file, inputFiles.get(file).sha256, 'public input: ' + file, false)
      if (found) inputs.set(file, found)
    }
    if (sourceScope.length && !problems.length)
      componentResolverBoundary(root, inputFiles, problems)
  } catch (error) {
    problems.push(
      'public output inspection failed: ' + (error instanceof Error ? error.name : 'unknown error')
    )
  }
  return result
}
