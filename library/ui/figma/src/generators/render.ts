type Renderable = string | number | boolean | Renderable[] | { [key: string]: Renderable }

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

function quote(value: string): string {
  const escaped = value.replace(/\\/g, '\\\\')
  if (escaped.includes("'") && !escaped.includes('"')) return `"${escaped}"`
  return `'${escaped.replace(/'/g, "\\'")}'`
}

const renderKey = (key: string) => (IDENTIFIER.test(key) || /^\d+$/.test(key) ? key : quote(key))

function renderValue(value: Renderable, depth = 0): string {
  if (typeof value === 'string') return quote(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  const pad = '  '.repeat(depth + 1)
  const closePad = '  '.repeat(depth)
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    return `[\n${value.map((item) => `${pad}${renderValue(item, depth + 1)}`).join(',\n')}\n${closePad}]`
  }
  const entries = Object.entries(value)
  if (entries.length === 0) return '{}'
  return `{\n${entries
    .map(([key, item]) => `${pad}${renderKey(key)}: ${renderValue(item, depth + 1)}`)
    .join(',\n')}\n${closePad}}`
}

// Names the tool, never the Figma file: the file key is private.
function header(): string {
  return '// Generated by dcl-figma from the Figma design system snapshot. Do not edit: changes are overwritten on sync.\n'
}

export { header, renderValue }
export type { Renderable }
